-- ==========================================================================
--  Library Book Management System -- database creation script
--  Works with MySQL 8.0.16+ and MariaDB 10.4+ (e.g. XAMPP).
--
--  Run it with ONE of:
--    flask init-db                         (from the project folder)
--    mysql -u root -p < database.sql       (MySQL command line)
--    phpMyAdmin -> Import -> choose this file
--
--  The script is safe to run more than once: it never drops data, and the
--  sample rows are inserted with INSERT IGNORE (skipped if already present).
-- ==========================================================================

CREATE DATABASE IF NOT EXISTS library_db
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE library_db;

-- --------------------------------------------------------------------------
--  Table: book
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS book (
    book_id           INT           NOT NULL AUTO_INCREMENT,
    title             VARCHAR(255)  NOT NULL,
    author            VARCHAR(255)  NOT NULL,
    isbn              VARCHAR(20)   NOT NULL,
    category          VARCHAR(100)  NOT NULL,
    publisher         VARCHAR(255)  NULL,
    publication_year  INT           NULL,
    quantity          INT           NOT NULL DEFAULT 0,
    shelf_location    VARCHAR(100)  NOT NULL,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
                                    ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT pk_book            PRIMARY KEY (book_id),
    CONSTRAINT uq_book_isbn       UNIQUE (isbn),
    CONSTRAINT chk_book_quantity  CHECK (quantity >= 0),
    CONSTRAINT chk_book_year      CHECK (publication_year IS NULL
                                         OR publication_year BETWEEN 1000 AND 2100),
    CONSTRAINT chk_book_title     CHECK (CHAR_LENGTH(TRIM(title)) > 0),
    CONSTRAINT chk_book_author    CHECK (CHAR_LENGTH(TRIM(author)) > 0),

    INDEX idx_book_title    (title),
    INDEX idx_book_author   (author),
    INDEX idx_book_category (category)
) ENGINE = InnoDB;

-- --------------------------------------------------------------------------
--  Table: librarian  (accounts allowed to use the system)
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS librarian (
    librarian_id   INT           NOT NULL AUTO_INCREMENT,
    username       VARCHAR(50)   NOT NULL,
    full_name      VARCHAR(100)  NOT NULL,
    password_hash  VARCHAR(255)  NOT NULL,
    role           ENUM('admin', 'librarian') NOT NULL DEFAULT 'librarian',
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_librarian           PRIMARY KEY (librarian_id),
    CONSTRAINT uq_librarian_username  UNIQUE (username)
) ENGINE = InnoDB;

